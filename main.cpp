math_vector<double> make_digit(const char (&pixels)[N])
{
    static_assert(N == 28 * 28 + 1);

    math_vector<double> result(28 * 28, 0);

    for (std::size_t i = 0; i < result.size(); ++i)
        result[i] = pixels[i] == '#' ? 1 : 0;

    return result;
}

